"""QA pack of a work item: docs/qa/<REQ>/.

Each tester writes its own report (functional, security, exploratory, uat, performance) whose first line is
`Verdict: PASS|FAIL|PARTIAL`. `sdlc test-report` writes defects.md (the defect log, from state) and summary.md
(verdicts, defects, exit criteria, coverage). Approving the QA gate writes the sign-off into summary.md.
"""

import re
from pathlib import Path
from typing import Any

from . import events, generate, state, trace

REPORTS = {"functional": "Functional, integration, regression, error states", "security": "Security",
           "exploratory": "Exploratory and API compatibility", "uat": "UAT",
           "ui": "UI, UX journeys, loading, accessibility, browsers and devices", "performance": "Performance"}
OPTIONAL = {"ui"}  # only for work items with a user interface
SIGNOFF = "## Sign-off"


def pack(root: Path, req: str) -> Path:
    return root / "docs" / "qa" / req


def new_pack(root: Path, req: str, title: str, ui: bool = False) -> list[Path]:
    out = []
    for name in REPORTS:
        if name in OPTIONAL and not ui:
            continue
        p = pack(root, req) / f"{name}.md"
        if not p.exists():
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(generate.render(f"qa/{name}.md", root, req=req, title=title))
        out.append(p)
    return out


def verdict(p: Path) -> str:
    if not p.exists():
        return "missing"
    first = p.read_text().splitlines()[:1]
    # One verdict chosen: the template's "PASS / FAIL / PARTIAL" placeholder is not a verdict
    m = re.match(r"Verdict:\s*(PASS|FAIL|PARTIAL|N/A)\b(?!\s*/)", first[0].strip(), re.I) if first else None
    return m.group(1).upper() if m else "not filled"


def _exit_criteria(root: Path, req: str) -> str:
    p = root / "docs" / "plan" / req / "test-plan.md"
    m = re.search(r"^- Done when:\s*(.+)$", p.read_text(), re.M) if p.exists() else None
    return m.group(1).strip() if m else ""


def build(root: Path, req: str) -> dict[str, Any]:
    item = state.load(root, req)
    verdicts = {name: verdict(pack(root, req) / f"{name}.md") for name in REPORTS
                if name not in OPTIONAL or (pack(root, req) / f"{name}.md").exists()}
    defects = item.get("defects", [])
    t = trace.build(root, req)
    c = item.get("checks")
    blockers = state.open_blocker_defects(item)
    criteria = [
        ("Every test report is PASS (or N/A)", all(v in ("PASS", "N/A") for v in verdicts.values())),
        ("No open release-blocking defects", not blockers),
        ("Every must acceptance criterion has a test", not t["uncovered_must"]),
        ("Checks passed after the last change", bool(c and c["passed"])),
    ]
    return {"item": item, "verdicts": verdicts, "defects": defects, "trace": t, "checks": c, "blockers": blockers,
            "criteria": criteria, "plan_exit": _exit_criteria(root, req), "met": all(ok for _, ok in criteria)}


def _defect_rows(defects: list[dict[str, Any]]) -> list[str]:
    rows = ["| ID | Defect | Severity | Blocker | Status | Fix task | Found by |", "| --- | --- | --- | --- | --- | --- | --- |"]
    for d in defects:
        status = d["status"] + (f" of {d['duplicate_of']}" if d.get("duplicate_of") else "")
        rows.append(f"| {d['id']} | {d['title'].replace('|', '/')} | {d['severity']} | {'yes' if d['blocker'] else 'no'} | "
                    f"{status} | {d['task'] or '-'} | {d['found_by'] or '-'} |")
    return rows if defects else rows + ["| - | No defects recorded | | | | | |"]


def write(root: Path, req: str) -> tuple[Path, dict[str, Any]]:
    r = build(root, req)
    item, d = r["item"], pack(root, req)
    d.mkdir(parents=True, exist_ok=True)
    log = [f"# Defect log: {req} {item['title']}", "", f"Generated by `sdlc test-report {req}` from the work item; "
           "change defects with `sdlc defect`.", "", *_defect_rows(r["defects"])]
    for x in r["defects"]:
        log += ["", f"## {x['id']}: {x['title']}", ""]
        log += [f"- {e['ts'][:16].replace('T', ' ')} · {e['action']}" + (f" by {e['by']}" if e.get("by") else "")
                + (f": {e['note']}" if e.get("note") else "") for e in x["log"]]
    (d / "defects.md").write_text("\n".join(log) + "\n")

    counts = {s: sum(x["severity"] == s and x["status"] in state.D_OPEN for x in r["defects"]) for s in state.SEVERITIES}
    t = r["trace"]
    lines = [f"# Test report: {req} {item['title']}", "",
             f"Exit criteria **{'met' if r['met'] else 'NOT met'}**. Generated by `sdlc test-report {req}`; "
             "the sign-off below is written when the QA gate is approved.", "",
             "## Results", "", "| Testing | Report | Verdict |", "| --- | --- | --- |"]
    lines += [f"| {label} | [{name}.md]({name}.md) | {r['verdicts'][name]} |" for name, label in REPORTS.items()
              if name in r["verdicts"]]
    lines += ["", "## Defects", "",
              "Open: " + ", ".join(f"{n} {s}" for s, n in counts.items() if n) if any(counts.values()) else "No open defects.",
              f"Release blockers open: {', '.join(r['blockers']) or 'none'}. Full log: [defects.md](defects.md).", "",
              *_defect_rows(r["defects"]),
              "", "## Exit criteria", "", "| Criterion | Met |", "| --- | --- |"]
    lines += [f"| {name} | {'yes' if ok else '**no**'} |" for name, ok in r["criteria"]]
    if r["plan_exit"]:
        lines += ["", f"Test plan: {r['plan_exit']}"]
    lines += ["", "## Coverage", "",
              f"- {sum(x['covered'] for x in t['rows'])}/{len(t['rows'])} acceptance criteria have tests "
              f"([traceability](../../rtm/{req}.md))",
              f"- Checks: {'passed' if r['checks'] and r['checks']['passed'] else 'not passed'}"
              + (f" at `{r['checks']['head']}`" if r["checks"] else "") + f" ([report](../../dev/{req}/checks.md))"]
    summary = d / "summary.md"
    old = summary.read_text() if summary.exists() else ""
    kept = old[old.index(SIGNOFF):] if SIGNOFF in old else f"{SIGNOFF}\n\nNot signed off yet.\n"
    summary.write_text("\n".join(lines) + "\n\n" + kept)
    return summary, r


def record_signoff(root: Path, req: str, by: str, comment: str) -> list[str]:
    summary = pack(root, req) / "summary.md"
    if not summary.exists():
        return []
    when = events.now()[:16].replace("T", " ")
    text = summary.read_text()
    head = text[:text.index(SIGNOFF)] if SIGNOFF in text else text
    open_items = [x["id"] for x in state.load(root, req).get("defects", []) if x["status"] in state.D_OPEN]
    line = f"Signed off by {by} on {when}" + (f": {comment}" if comment else "") + "."
    if open_items:
        line += f" Released with open non-blocking defects: {', '.join(open_items)}."
    summary.write_text(f"{head}{SIGNOFF}\n\n{line}\n")
    return [str(summary.relative_to(root))]
