"""QA handover for a work item: docs/dev/<REQ>/handover.md.

The top part is generated from the repo and state (build, how to run, changes, migrations, config, tasks and
reviews, checks, traceability) and is rewritten on every `sdlc handover`. The sections below the marker
(how to verify, test data, known limitations) are written by the dev-integration-verifier and kept as they are.
"""

import re
from collections import Counter
from pathlib import Path
from typing import Any

from . import checks, config, gitops, state, trace

END = "<!-- agentic-sdlc:handover-generated-end -->"
OLD_END = "<!-- sdlc-pilot:handover-generated-end -->"  # handovers written before the rename
AGENT_PART = """
## How to verify
<!-- Filled by the dev-integration-verifier: the steps QA follows, per acceptance criterion or UAT scenario. -->

## Test data
<!-- Filled by the dev-integration-verifier: data to load or create, accounts, fixtures. -->

## Known limitations
<!-- Filled by the dev-integration-verifier: what does not work yet, deferred items, open findings. "none" if none. -->
"""
MIGRATION = re.compile(r"(^|/)(migrations?|alembic|db/migrate|schema)/|\.sql$")
CONFIG = re.compile(r"(^|/)(\.env\.example|\.env\.sample|config/|settings\.|.*\.ya?ml$|.*\.toml$)")


def _git(root: Path, *args: str) -> str:
    try:
        return gitops.git(root, *args)
    except gitops.GitError:
        return ""


def build(root: Path, req: str, cfg: dict[str, Any]) -> str:
    item = state.load(root, req)
    base = checks._base(root)
    head = _git(root, "rev-parse", "--short", "HEAD").strip()
    branch = _git(root, "rev-parse", "--abbrev-ref", "HEAD").strip()
    commits = _git(root, "rev-list", "--count", f"{base}..HEAD").strip() if base else ""
    numstat = _git(root, "diff", "--numstat", f"{base}...HEAD") if base else ""
    files, added, removed, by_dir, sdlc_docs = [], 0, 0, Counter(), 0
    for line in numstat.splitlines():
        a, d, path = line.split("\t", 2)
        files.append(path)
        added += int(a) if a.isdigit() else 0
        removed += int(d) if d.isdigit() else 0
        if gitops.managed(path):
            sdlc_docs += 1  # specs, design, plan, evidence: counted apart from the code
            continue
        by_dir[path.split("/", 1)[0] if "/" in path else "(root)"] += 1
    c = item.get("checks")
    t = trace.build(root, req)
    covered = sum(r["covered"] for r in t["rows"])
    reviews = {}
    for task in item["tasks"]:
        p = root / ".sdlc" / "reviews" / f"{req}-{task['id']}.md"
        reviews[task["id"]] = p.read_text().splitlines()[0].removeprefix("Verdict:").strip() if p.exists() else "-"

    lines = [f"# QA handover: {req} {item['title']}", "",
             f"Type: {state.item_type(item)}. The part above the marker is generated by `sdlc handover {req}`.", "",
             "## Build",
             f"- Branch: `{branch or '-'}` at `{head or '-'}`" + (f", {commits} commits since `{base[:7]}`" if base else ""),
             f"- Checks: {'passed' if c and c['passed'] else 'FAILED' if c else 'not run'}"
             + (f" at `{c['head']}`" if c else "") + f" ([report](checks.md))",
             f"- Traceability: {covered}/{len(t['rows'])} acceptance criteria have tests ([matrix](../../rtm/{req}.md))",
             "", "## How to run"]
    comps = config.components(cfg)
    for c in comps:
        cmds = c["commands"]
        if c["name"]:
            lines.append(f"- **{c['name']}** ({c['kind']}, in `{c['path']}/`):")
        pad = "  " if c["name"] else ""
        for key, label in (("install", "Install"), ("run", "Run"), ("deploy_test", "Deploy to test"),
                           ("test", "Test"), ("e2e", "End-to-end tests")):
            if cmds.get(key):
                lines.append(f"{pad}- {label}: `{cmds[key]}`")
        if not any(cmds.get(k) for k in ("run", "dev", "deploy_test")):
            lines.append(f"{pad}- Run: not configured (add `run` to its commands)")
    if len(comps) > 1:
        lines.append("- Start every component that runs (backend first), and point the frontend at the backend's URL.")
    lines += ["", "## Changes",
              f"- Code: {len(files) - sdlc_docs} files ("
              + (", ".join(f"{d} {n}" for d, n in by_dir.most_common()) or "none") + f"); SDLC documents: {sdlc_docs} files; "
              f"+{added} / -{removed} lines in all",
              "- Migrations: " + (", ".join(f"`{f}`" for f in files if MIGRATION.search(f)) or "none"),
              "- Configuration: " + (", ".join(f"`{f}`" for f in files if CONFIG.search(f) and not f.startswith("docs/"))
                                     or "none"),
              "", "## Tasks", "", "| Task | Title | Area | Review |", "| --- | --- | --- | --- |"]
    for task in item["tasks"]:
        title = task["title"] if len(task["title"]) <= 90 else task["title"][:87].rstrip() + "..."
        lines.append(f"| {task['id']} | {title.replace('|', '/')} | {task.get('area') or '-'} | {reviews[task['id']]} |")
    docs = [p for p in (f"specs/{req}.md", f"docs/design/{req}/README.md", f"docs/adr/ADR-{req}.md",
                        f"docs/plan/{req}/test-plan.md", f"docs/plan/{req}/release-plan.md",
                        f"docs/dev/{req}/verification.md") if (root / p).exists()]
    lines += ["", "## Documents", *[f"- `{p}`" for p in docs], "", END]
    return "\n".join(lines) + "\n"


def write(root: Path, req: str, cfg: dict[str, Any]) -> Path:
    p = root / "docs" / "dev" / req / "handover.md"
    p.parent.mkdir(parents=True, exist_ok=True)
    old = p.read_text().replace(OLD_END, END) if p.exists() else ""
    kept = old.split(END, 1)[1] if END in old else AGENT_PART
    p.write_text(build(root, req, cfg) + kept)
    return p
