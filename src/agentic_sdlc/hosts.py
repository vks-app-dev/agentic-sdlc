"""One agent source, several AI tools.

The agents are defined once, in Agentic SDLC's `plugin/agents/*.md` (Claude Code reads them through the plugin).
`sdlc agents export --host copilot` turns the same files into what GitHub Copilot reads in a repository:

    .github/agents/<agent>.agent.md     one custom agent per Agentic SDLC agent, plus `sdlc-orchestrator`
    .github/prompts/sdlc-*.prompt.md    /sdlc-run, /sdlc-new, /sdlc-status in Copilot chat
    .vscode/mcp.json                    the `sdlc mcp` server, so Copilot can call the engine as tools
    AGENTS.md                           the project rules section (Copilot and other tools read AGENTS.md)

Generated files carry a marker; re-exporting overwrites only those, never a file a team wrote itself.
Copilot-specific differences are stated in a short "host notes" block at the top of each agent.
"""

import json
import re
from pathlib import Path
from typing import Any

from . import generate

from .paths import plugin_dir

PLUGIN = plugin_dir()
MARKER = "<!-- generated by Agentic SDLC (sdlc agents export); edit the source agent and re-export -->"
HOSTS = ("claude", "copilot")
# Claude Code tool names → Copilot's primary aliases (Copilot also accepts the Claude names)
TOOLS = {"Read": "read", "Grep": "search", "Glob": "search", "Write": "edit", "Edit": "edit", "MultiEdit": "edit",
         "NotebookEdit": "edit", "Bash": "execute", "Agent": "agent", "Task": "agent", "WebFetch": "web",
         "WebSearch": "web"}
MCP_TOOLS = "agentic-sdlc/*"

WORKER_NOTES = """> **Host notes (GitHub Copilot).** Run `sdlc …` commands in the terminal, or call the matching `agentic-sdlc` MCP
> tool. Agentic SDLC's Claude Code hooks do not run here, so the engine enforces the rules itself: never try to
> approve, reject, retype, skip, defer or accept a defect, unblock a task or deploy to production; ask a person."""

WORKTREE_NOTES = """> **No automatic worktree here.** Before anything else, create your own and work only inside it:
> `git worktree add ../$(basename $PWD)-worktrees/REQ-xxx-Tn -b sdlc/REQ-xxx-Tn sdlc/REQ-xxx`
> (or `git worktree add ../$(basename $PWD)-worktrees/REQ-xxx-Tn sdlc/REQ-xxx-Tn` on a retry)."""

ORCHESTRATOR_NOTES = """> **Host notes (GitHub Copilot).** Dispatch each step's agent with the `agent` tool, using its plain name
> (`dev-coder`, not `agentic-sdlc:dev-coder`). If this environment cannot run sub-agents, do each step yourself by
> following `.github/agents/<agent>.agent.md`, one agent at a time, in the order of the groups. A step's `model` is a
> recommendation; Copilot uses the model chosen in its model picker unless the agent file sets one. Run `sdlc`
> commands in the terminal or call the `agentic-sdlc` MCP tools. Copilot has no Agentic SDLC hooks: the engine itself
> refuses human-only actions and production deploys, so when one is needed, stop and tell the person."""


def _frontmatter(text: str) -> tuple[dict[str, str], str]:
    m = re.match(r"^---\n(.*?)\n---\n?(.*)$", text, re.S)
    if not m:
        return {}, text
    fields = {}
    for line in m.group(1).splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            fields[k.strip()] = v.strip()
    return fields, m.group(2)


def _yaml_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)  # a JSON string is valid YAML and quotes everything safely


def _write(path: Path, text: str) -> str:
    """Write a generated file unless a person-made file (no marker) is already there."""
    if path.exists() and MARKER not in path.read_text():
        return f"kept {path.as_posix()} (not generated by Agentic SDLC)"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return f"wrote {path.as_posix()}"


def copilot_agent(source: Path, cfg: dict[str, Any]) -> tuple[str, str]:
    fm, body = _frontmatter(source.read_text())
    name = fm["name"]
    tools = sorted({TOOLS.get(t.strip(), t.strip().lower()) for t in fm.get("tools", "").split(",") if t.strip()})
    tools.append(MCP_TOOLS)
    lines = ["---", f"name: {name}", f"description: {_yaml_str(fm.get('description', name))}",
             f"tools: {json.dumps(tools)}", "user-invocable: false"]  # run by the orchestrator, not picked by hand
    model = ((cfg.get("models") or {}).get("copilot") or {}).get(fm.get("model", ""))
    if model:
        lines.append(f"model: {_yaml_str(model)}")
    notes = WORKER_NOTES + ("\n\n" + WORKTREE_NOTES if fm.get("isolation") == "worktree" else "")
    return name, "\n".join(lines) + "\n---\n" + MARKER + "\n\n" + notes + "\n\n" + body.lstrip("\n")


def _command_body(name: str) -> str:
    fm, body = _frontmatter((PLUGIN / "commands" / f"{name}.md").read_text())
    return body.strip()


def orchestrator(cfg: dict[str, Any]) -> str:
    body = _command_body("sdlc-run").replace("`$0`", "the work item named in the request").replace(
        "$0", "<REQ>").replace("`$ARGUMENTS`", "the request").replace("agentic-sdlc:", "")
    tools = ["read", "search", "edit", "execute", "agent", MCP_TOOLS]
    return ("---\nname: sdlc-orchestrator\ndescription: " + _yaml_str(
        "Agentic SDLC orchestrator: runs a work item (REQ-xxx) through its stages with the Agentic SDLC agents and "
        "stops at human gates.") + f"\ntools: {json.dumps(tools)}\n---\n{MARKER}\n\n{ORCHESTRATOR_NOTES}\n\n{body}\n")


PROMPTS = {
    "sdlc-run": ("Run Agentic SDLC's agents for a work item until the next human gate", "<REQ-xxx> [--auto]",
                 "Run Agentic SDLC for work item ${input:req:REQ-001} (anything after the command is part of the "
                 "request). Follow your instructions as the sdlc-orchestrator."),
    "sdlc-new": ("Create a new Agentic SDLC work item and its spec", "<title of the work>", None),
    "sdlc-status": ("Show the Agentic SDLC pipeline board", "[REQ-xxx]", None),
}


def prompt_file(name: str) -> str:
    desc, hint, text = PROMPTS[name]
    agent = "sdlc-orchestrator" if name == "sdlc-run" else "agent"
    if text is None:
        text = (_command_body(name).replace("`$ARGUMENTS`", "the text after the command")
                .replace("$ARGUMENTS", "the text after the command"))
    return (f"---\nname: {name}\ndescription: {_yaml_str(desc)}\nargument-hint: {_yaml_str(hint)}\nagent: {agent}\n"
            f"---\n{MARKER}\n\n{text}\n")


def mcp_config(root: Path) -> str:
    """Add the agentic-sdlc server to .vscode/mcp.json (VS Code format: top-level `servers`), keeping the rest."""
    p = root / ".vscode" / "mcp.json"
    data = json.loads(p.read_text()) if p.exists() and p.read_text().strip() else {}
    data.setdefault("servers", {})["agentic-sdlc"] = {"type": "stdio", "command": "sdlc", "args": ["mcp"]}
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(data, indent=2) + "\n")
    return f"wrote {p.relative_to(root).as_posix()} (agentic-sdlc server)"


def export_copilot(root: Path, cfg: dict[str, Any]) -> list[str]:
    done = []
    for src in sorted((PLUGIN / "agents").glob("*.md")):
        name, text = copilot_agent(src, cfg)
        done.append(_write(root / ".github" / "agents" / f"{name}.agent.md", text))
    done.append(_write(root / ".github" / "agents" / "sdlc-orchestrator.agent.md", orchestrator(cfg)))
    for name in PROMPTS:
        done.append(_write(root / ".github" / "prompts" / f"{name}.prompt.md", prompt_file(name)))
    done.append(mcp_config(root))
    done.append(f"AGENTS.md: {generate.write_rules_file(root, cfg, 'AGENTS.md')}")
    return [d.replace(str(root) + "/", "") for d in done]
